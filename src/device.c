#define LIGHTING_SEQ_LEN (sizeof(lighting_seq) / sizeof(lighting_seq[0]))

static hid_device *dev = NULL;
static bool hid_ready = false;

static bool ensure_hid_init(void)
{
    if (!hid_ready) {
        if (hid_init() != 0)
            return false;
        hid_ready = true;
    }
    return true;
}

bool bvp_device_is_open(void) { return dev != NULL; }

bool bvp_device_open(void)
{
    if (dev)
        return true;
    if (!ensure_hid_init())
        return false;
    dev = hid_open(BVP_VID, BVP_PID, NULL);
    if (dev)
        hid_set_nonblocking(dev, 1);
    return dev != NULL;
}

void bvp_device_close(void)
{
    if (dev) {
        hid_close(dev);
        dev = NULL;
    }
}

/* A failed write almost always means the device was unplugged: close
   so the next poll retries opening it. */
static bool write_report(const uint8_t *buf, size_t len)
{
    if (!dev && !bvp_device_open())
        return false;
    if (hid_write(dev, buf, len) < 0) {
        bvp_device_close();
        return false;
    }
    return true;
}

bvp_status bvp_device_poll(void)
{
    bvp_status st = { false, BVP_BAT_UNKNOWN, -1 };

    if (!dev && !bvp_device_open())
        return st;
    st.dongle_present = true;

    const uint8_t req[2] = { 0xC9, 0x64 };
    if (hid_write(dev, req, sizeof(req)) < 0) {
        bvp_device_close();
        st.dongle_present = false;
        return st;
    }

    uint8_t buf[64];
    int n = -1;
    for (int i = 0; i < 20 && n <= 0; i++) {   /* non-blocking: retry */
        n = hid_read_timeout(dev, buf, sizeof(buf), 25);
        if (n < 0) {
            bvp_device_close();
            st.dongle_present = false;
            return st;
        }
    }
    if (n < 5)
        return st;   /* dongle there, but no usable reply */

    st.percent = buf[2] & 0x7F;
    switch (buf[4]) {
    case 0:  st.state = BVP_BAT_DISCONNECTED; st.percent = -1; break;
    case 1:  st.state = BVP_BAT_NORMAL;   break;
    case 2:  st.state = BVP_BAT_LOW;      break;
    case 4:
    case 5:  st.state = BVP_BAT_CHARGING; break;
    default: st.state = BVP_BAT_NORMAL;   break;
    }
    return st;
}

static bool send_lighting(uint8_t r, uint8_t g, uint8_t b, uint8_t level)
{
    uint8_t seq[LIGHTING_SEQ_LEN][REPORT_LEN];
    for (size_t i = 0; i < LIGHTING_SEQ_LEN; i++)
        memcpy(seq[i], lighting_seq[i].data, REPORT_LEN);

    for (size_t i = 0; i < LIGHTING_SEQ_LEN; i++) {
        if (seq[i][0] != 0xcb)
            continue;
        int pairs = seq[i][1];
        for (int k = 0; k < pairs && 3 + 2 * k < REPORT_LEN; k++) {
            uint8_t *reg = &seq[i][2 + 2 * k];
            switch (reg[0]) {
            case 0x53: if (pairs == 9) reg[1] = r; break;   /* red */
            case 0x5f: reg[1] = g; break;                   /* green */
            case 0x6b: reg[1] = b; break;                   /* blue */
            case 0x2c: case 0x26: case 0x27:
            case 0x2d: case 0x28: case 0x29:
                if (pairs == 6) reg[1] = level;             /* brightness */
                break;
            default: break;
            }
        }
    }

    for (size_t i = 0; i < LIGHTING_SEQ_LEN; i++) {
        usleep(lighting_seq[i].gap_ms * 1000);
        /* One report (the 0xFF microphone block) is rejected by hidapi and
           is unrelated to lighting; a failure there must not abort. */
        if (!write_report(seq[i], REPORT_LEN) && seq[i][0] != 0xff)
            return false;
    }
    return true;
}

static uint8_t last_r = 0, last_g = 0, last_b = 255, last_level = 200;

bool bvp_device_set_color(uint8_t r, uint8_t g, uint8_t b)
{
    last_r = r; last_g = g; last_b = b;
    return send_lighting(r, g, b, last_level);
}

bool bvp_device_set_brightness(uint8_t level)
{
    last_level = level;
    return send_lighting(last_r, last_g, last_b, level);
}

bool bvp_device_set_lighting(uint8_t r, uint8_t g, uint8_t b, uint8_t level)
{
    last_r = r; last_g = g; last_b = b; last_level = level;
    return send_lighting(r, g, b, level);
}

const char *bvp_state_label(bvp_battery_state s)
{
    switch (s) {
    case BVP_BAT_NORMAL:       return "on battery";
    case BVP_BAT_LOW:          return "battery low";
    case BVP_BAT_CHARGING:     return "charging";
    case BVP_BAT_DISCONNECTED: return "headset off";
    default:                   return "state unknown";
    }
}
